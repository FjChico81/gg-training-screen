/**
 * HF · Read-only adapter from the saved workout format to a collective display.
 * No database, cloud, storage, DOM or network operations in this module.
 * The original workout object is NEVER modified.
 */
import {buildHFAdvancedGuided} from './hf-advanced-class.mjs';
export class HFPresentationError extends Error {
  constructor(message) { super(message); this.name='HFPresentationError'; }
}
const fail=msg=>{throw new HFPresentationError(msg)};
const MAX_STEPS=200;
const MAX_BLOCKS=200;
const MAX_LINE=500;
const ADVANCED=/\b(?:AMRAP|FOR TIME|EMOM)\b/i;
const INTERVALS=/\bintervalos?\b/i;
const RESERVED=/^\s*(?:descanso|recuperaci[oó]n)\b/i;
const timematch=/^(.*)\s+@([0-9]+)$/;
const gifmatch=/ \| GIF ([a-z0-9-]+)(?= @\d+$|$)/;
const number=/\d+(?:[.,]\d+)?/;
const units='(?:km|kcal|metros?|kil[oó]metros?|min(?:utos?)?\\.?|seg(?:undos?)?\\.?|s|m)';
function validateSource(w) {
  if(!w||typeof w!=='object'||typeof w.name!=='string'||!w.name.trim()
    ||w.name.length>120||!Array.isArray(w.blocks)||!w.blocks.length||w.blocks.length>MAX_BLOCKS)
    fail('La rutina no tiene una estructura compatible.');
  let count=0;
  for(const block of w.blocks){
    if(!block||typeof block.name!=='string'||!block.name.trim()||!Array.isArray(block.items)
      ||!block.items.length)fail('Hay un bloque sin nombre o ejercicios.');
    for(const line of block.items){
      count++;
      if(typeof line!=='string'||!line.trim()||line.length>MAX_LINE)
        fail('Hay ejercicios vacíos o incorrectos.');
    }
  }
  if(count>MAX_STEPS)fail('Esta rutina supera el límite de 200 ejercicios.');
}
function decodeLine(raw) {
  const matchedGif=raw.match(gifmatch);
  const gifId=matchedGif?.[1]||null;
  const cleaned=matchedGif?raw.replace(matchedGif[0],''):raw;
  const t=cleaned.match(timematch);
  let label=(t?t[1]:cleaned).trim();
  const seconds=t?Number(t[2]):0;
  if(t&&(!Number.isInteger(seconds)||seconds<1||seconds>7200))
    fail('Hay una duración fuera de 1–7200 segundos.');
  if(label.length===0||label.length>220)fail('El nombre del ejercicio está vacío o es demasiado largo.');
  const rest=RESERVED.test(label);
  if(rest&&!t)fail('Hay un descanso sin tiempo @segundos; revísalo en el editor HF.');
  return {label,seconds,rest,gifId};
}
function short(value,max,label){
  const text=String(value||'').trim();
  if(!text||text.length>max)fail(label+' no cabe en la pantalla; acorta ese campo en el editor.');
  return text;
}
function targetOf(label){
  const trimmed=label.trim();
  // Common cardio formats generated by the HF editor.
  const amountFirst=trimmed.match(new RegExp('^('+number.source+')\\s*('+units+')\\s+(?:de\\s+)?(.+)$','i'));
  if(amountFirst){
    return {name:amountFirst[3].trim(),target:amountFirst[1]+' '+amountFirst[2]};
  }
  const amountLast=trimmed.match(new RegExp('^(.+?)\\s*[·,|]\\s*('+number.source+')\\s*('+units+')$','i'));
  if(amountLast){
    return {name:amountLast[1].trim(),target:amountLast[2]+' '+amountLast[3]};
  }
  const reps=trimmed.match(/^(\d{1,4})\s+(.+)$/);
  if(reps)return {name:reps[2].trim(),target:reps[1]+' repeticiones'};
  return {name:trimmed,target:'Avance manual'};
}
function strengthOf(label){
  // HF supported format: Exercise | 3x10 | 25kg | RIR 2 | descanso 90s.
  const parts=label.split('|').map(x=>x.trim());
  let name=parts[0],sets=0,reps=0,weight='',rir='',rest=null;
  const legacy=name.match(/^(\d+)\s*[x×]\s*(\d+)\s+(.+)$/i);
  if(legacy){sets=Number(legacy[1]);reps=Number(legacy[2]);name=legacy[3];}
  // Cardio also uses pipes: Carrera | 400 m.
  if(!legacy&&!parts.slice(1).some(part=>/^\d+\s*[x×]\s*\d+$/i.test(part)))return null;
  for(const part of parts.slice(1)){
    let m=part.match(/^(\d+)\s*[x×]\s*(\d+)$/i);
    if(m){sets=Number(m[1]);reps=Number(m[2]);continue;}
    m=part.match(/^(\d+(?:[.,]\d+)?)\s*kg$/i);
    if(m){weight=m[1]+' kg';continue;}
    m=part.match(/^RIR\s*(\d+)$/i);
    if(m){rir='RIR '+m[1];continue;}
    m=part.match(/^descanso\s*(\d+)\s*s?$/i);
    if(m){rest=Number(m[1]);continue;}
    // Do not silently discard unrecognized workout directives.
    fail('Hay un dato de fuerza que no se puede representar: '+part);
  }
  if(!sets)return null;
  if(!Number.isInteger(sets)||sets<1||sets>30||!Number.isInteger(reps)||reps<1||reps>500)
    fail('Hay series o repeticiones de fuerza fuera de rango.');
  if(rest!==null&&(!Number.isInteger(rest)||rest<0||rest>1800))
    fail('Hay un descanso entre series fuera de rango.');
  return {name,sets,reps,weight,rir,rest};
}
function itemToSteps(raw,block) {
  const {label,seconds,rest,gifId}=decodeLine(raw);
  if(rest) {
    const title=label.length>70?label.slice(0,70):label;
    return [{name:'DESCANSO',target:short(title+' · '+seconds+' s',85,'Descanso'),seconds,gifId:null,block,kind:'rest'}];
  }
  const strength=strengthOf(label);
  if(strength) {
    if(seconds)fail('Una serie de fuerza tiene simultáneamente tiempo y series. Revísala.');
    const out=[];
    const details=[strength.reps+' repeticiones',strength.weight,strength.rir].filter(Boolean).join(' · ');
    for(let i=0;i<strength.sets;i++){
      out.push({
        name:short(strength.name,60,'Ejercicio'),
        target:short('Serie '+(i+1)+'/'+strength.sets+' · '+details,85,'Objetivo'),
        seconds:0,gifId,block,kind:'exercise'
      });
      // Strictly only a rest EXPLICITLY present in the stored workout.
      if(i<strength.sets-1&&strength.rest>0){
        out.push({name:'DESCANSO',target:'Entre series · '+strength.rest+' s',
          seconds:strength.rest,gifId:null,block,kind:'rest'});
      }
    }
    return out;
  }
  const metric=targetOf(label);
  const name=short(metric.name,60,'Ejercicio');
  const target=seconds?
    short((metric.target==='Avance manual'?'':metric.target+' · ')+seconds+' segundos',85,'Objetivo'):
    short(metric.target,85,'Objetivo');
  return [{name,target,seconds,gifId,block,kind:'exercise'}];
}
function checkComplex(w){
  const names=w.blocks.map(b=>b.name);
  if(names.some(n=>ADVANCED.test(n)))
    fail('La rutina contiene AMRAP, EMOM o FOR TIME. Usa el modo guiado original de HF hasta que esté integrada esa lógica específica en la pantalla colectiva.');
}
export function toHFPresentation(workout,mode='guided') {
  validateSource(workout);
  if(mode==='stations')checkComplex(workout);
  const title=short(workout.name,120,'Nombre de la rutina');
  if(mode==='guided') {
    let built;
    try{built=buildHFAdvancedGuided(workout,itemToSteps)}
    catch(error){fail(error?.message||'No se ha podido interpretar el formato avanzado.')}
    if(!built.guided.length)fail('La rutina no tiene pasos compatibles.');
    return {version:1,mode,title,plan:built,requiresReview:false,
      warnings:['Los ejercicios sin @segundos avanzan manualmente.',
        'AMRAP conserva su límite global y sus rondas; FOR TIME conserva el límite global (si existe); EMOM respeta los intervalos de un minuto.',
        'Solo se insertan descansos explícitos.']};
  }
  if(mode==='stations') {
    if(workout.blocks.length!==1)fail('Para estaciones, selecciona una rutina HF de un solo bloque con 2 a 8 ejercicios. No se fusionan bloques ni rondas automáticamente.');
    if(!Array.isArray(workout.blocks[0].items)||workout.blocks[0].items.length<2||workout.blocks[0].items.length>8)
      fail('El bloque debe incluir entre 2 y 8 estaciones.');
    if(INTERVALS.test(workout.blocks[0].name))
      fail('Los intervalos secuenciales no se convierten automáticamente en estaciones simultáneas.');
    const stations=workout.blocks[0].items.map(raw=>{
      const d=decodeLine(raw);
      if(d.seconds||d.rest)fail('El bloque tiene tiempos o descansos propios. No pueden imponerse como cronómetro común de estaciones.');
      const strength=strengthOf(d.label);
      const m=strength?{name:strength.name,target:
          [strength.sets+'×'+strength.reps,strength.weight,strength.rir].filter(Boolean).join(' · ')}:
          targetOf(d.label);
      return {name:short(m.name,60,'Estación'),target:short(m.target,85,'Objetivo'),gifId:d.gifId};
    });
    return {version:1,mode,title,plan:{stations,rounds:3,work:60,change:20},requiresReview:true,
      warnings:['Los valores 3 vueltas, 60 s de trabajo y 20 s de cambio son una propuesta, NO provienen de la rutina. Revísalos y confírmalos antes de iniciar.']};
  }
  fail('Formato de presentación desconocido.');
}
const KEY='hf-presentation-handoff-v1:';
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const TTL=10*60*1000;
export function createHFHandoff(workout,mode,{store,now=()=>Date.now(),uuid=()=>crypto.randomUUID()}){
  if(!store||typeof store.setItem!=='function')fail('El navegador no permite transferir esta clase.');
  const payload=toHFPresentation(workout,mode);
  const id=uuid();
  if(typeof id!=='string'||!UUID.test(id))
    fail('Identificador temporal no válido.');
  const createdAt=now();
  if(!Number.isSafeInteger(createdAt)||createdAt<0)fail('Hora de transferencia inválida.');
  const snapshot={...payload,createdAt};
  const raw=JSON.stringify(snapshot);
  if(raw.length>150000)fail('La clase es demasiado grande para una transferencia temporal.');
  store.setItem(KEY+id,raw);
  return id;
}
export function consumeHFHandoff(id,{store,now=()=>Date.now()}={}){
  if(typeof id!=='string'||!UUID.test(id))
    fail('Identificador temporal de clase inválido.');
  if(!store||typeof store.getItem!=='function')fail('Almacenamiento temporal no disponible.');
  const key=KEY+id;
  const raw=store.getItem(key);
  if(!raw)fail('No se ha encontrado la clase. Abre la rutina desde HF en esta misma pestaña.');
  let data;
  try{data=JSON.parse(raw);}catch{fail('La transferencia está dañada. Abre la rutina otra vez.');}
  const elapsed=now()-data.createdAt;
  if(!Number.isFinite(elapsed)||elapsed<0||elapsed>TTL)
    fail('La transferencia ha caducado. Abre de nuevo la rutina desde HF.');
  if(data.version!==1||!['guided','stations'].includes(data.mode)||typeof data.title!=='string'
    ||!data.plan||!Array.isArray(data.warnings)||typeof data.requiresReview!=='boolean')
    fail('La clase temporal no es compatible.');
  // Defense against a hand-edited sessionStorage payload.
  if(data.mode==='guided') {
    if(!Array.isArray(data.plan.guided)||data.plan.guided.length<1||data.plan.guided.length>MAX_STEPS)fail('Pasos incompatibles.');
    for(const e of data.plan.guided) {
      if(!e||typeof e.name!=='string'||e.name.length>60||typeof e.target!=='string'||e.target.length>85
        ||!Number.isInteger(e.seconds)||e.seconds<0||e.seconds>7200
        ||(e.gifId!==null&&e.gifId!==undefined&&!/^[a-z0-9-]+$/.test(e.gifId)))
        fail('La clase contiene un ejercicio inválido.');
    }
  }else{
    if(!Array.isArray(data.plan.stations)||data.plan.stations.length<2||data.plan.stations.length>8
      ||!Number.isInteger(data.plan.rounds)||data.plan.rounds<1||data.plan.rounds>12
      ||!Number.isInteger(data.plan.work)||data.plan.work<10||data.plan.work>1800
      ||!Number.isInteger(data.plan.change)||data.plan.change<0||data.plan.change>300)fail('Estaciones incompatibles.');
  }
  // Read-only of saved HF routines: do not touch their localStorage/Cloud records.
  return data;
}
